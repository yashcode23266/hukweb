function resolveNested(source, key) {
  return key.split('.').reduce((value, part) => value?.[part], source)
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('language') || 'en')

  useEffect(() => {
    localStorage.setItem('language', language)
    document.documentElement.lang = language === 'mr' ? 'mr' : 'en'
  }, [language])

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      toggleLanguage: () => setLanguage((current) => (current === 'en' ? 'mr' : 'en')),
      t: (key) => {
        const translated = resolveNested(translations[language], key)
        const fallback = resolveNested(translations.en, key)
        return typeof translated === 'string' ? translated : typeof fallback === 'string' ? fallback : key
      },
      tList: (key) => {
        const translated = resolveNested(translations[language], key)
        const fallback = resolveNested(translations.en, key)
        return Array.isArray(translated) ? translated : Array.isArray(fallback) ? fallback : []
      },
      tObject: (key) => {
        const translated = resolveNested(translations[language], key)
        const fallback = resolveNested(translations.en, key)
        return translated && typeof translated === 'object' && !Array.isArray(translated)
          ? translated
          : fallback && typeof fallback === 'object' && !Array.isArray(fallback)
            ? fallback
            : {}
      },
    }),
    [language],
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
